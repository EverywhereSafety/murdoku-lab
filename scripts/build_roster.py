"""Freeze the casebook portrait roster into murdoku_lab/visual/art/roster.py.

Looks are drawn once from a seeded search and then committed, so a name keeps its face across
releases. Rerun only to extend the roster; existing entries must stay in place.

    python scripts/build_roster.py
"""

import random
from pathlib import Path

from murdoku_lab.visual.art import portraits as P

OUT = Path(__file__).resolve().parents[1] / "murdoku_lab/visual/art/roster.py"
COUNTS = {"neutral": 64, "woman": 32, "man": 32}
MIN_DIFFERENCES = 3
SALIENT = (
    "hair",
    "hair_colour",
    "hat",
    "glasses",
    "facial",
    "earrings",
    "outfit",
    "skin",
)


def candidate(rng, pool, index):
    rules = P.POOL_RULES[pool]
    hair = rng.choice(rules["hair"])
    hat = rng.choice((1, 2, 3, 4, 5, 6)) if rng.random() < 0.32 else 0
    if P.HAIR_STYLES[hair] in ("afro", "bun", "braids", "ponytail"):
        hat = 0
    if hat == 5 and pool == "man":
        hat = 0
    glasses = rng.choice((1, 2, 3)) if rng.random() < 0.3 else 0
    if glasses == 3 and pool == "woman":
        glasses = 1
    facial = rng.choice(rules["facial"]) if pool == "man" and rng.random() < 0.55 else 0
    earrings = rng.choice((1, 2)) if pool == "woman" and rng.random() < 0.5 else 0
    extras = rng.choice(rules["extras"]) if rng.random() < 0.45 else 0
    hair_colour = rng.randrange(len(P.HAIR))
    if P.HAIR_STYLES[hair] == "bald":
        hair_colour = rng.choice((1, 2, 6, 7))
    return {
        "pool": pool,
        "face": rng.randrange(len(P.FACES)),
        # Skin tones cycle so every pool is balanced across tones.
        "skin": index % len(P.SKINS),
        "hair": hair,
        "hair_colour": hair_colour,
        "hat": hat,
        "glasses": glasses,
        "facial": facial,
        "earrings": earrings,
        "cut": rng.choice(rules["cuts"]),
        "outfit": rng.randrange(len(P.OUTFITS)),
        "background": rng.randrange(len(P.BACKGROUNDS)),
        "extras": extras,
    }


def differences(a, b):
    return sum(a[k] != b[k] for k in SALIENT)


def build(seed=7):
    rng = random.Random(seed)
    looks = []
    for pool, count in COUNTS.items():
        made = 0
        tries = 0
        while made < count:
            tries += 1
            look = candidate(rng, pool, made)
            if all(differences(look, other) >= MIN_DIFFERENCES for other in looks):
                looks.append(look)
                made += 1
            if tries > 200_000:
                raise RuntimeError(f"could not fill the {pool} pool")
    return looks


def main():
    looks = build()
    keys = (
        "pool",
        "face",
        "skin",
        "hair",
        "hair_colour",
        "hat",
        "glasses",
        "facial",
        "earrings",
        "cut",
        "outfit",
        "background",
        "extras",
    )
    lines = [
        '"""Frozen casebook portrait roster. Generated by scripts/build_roster.py; append only."""',
        "",
        "# (pool, face, skin, hair, hair_colour, hat, glasses, facial, earrings, cut, outfit,",
        "#  background, extras)",
        "LOOKS = (",
    ]
    for look in looks:
        values = ", ".join(repr(look[k]) for k in keys)
        lines.append(f"    ({values}),")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(looks)} looks to {OUT}")


if __name__ == "__main__":
    main()
