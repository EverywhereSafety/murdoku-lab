"""Design tokens shared by the casebook renderer and the player app.

    python -m murdoku_lab.visual.art.design_tokens --write   # refresh web/src/generated/
    python -m murdoku_lab.visual.art.design_tokens --check   # exit 1 if they drifted

One JSON document, and the same values as CSS custom properties, carries the day and night
palettes, the Everywhere Safety brand colours, the board and standee geometry, the person
accents and every setting's accent and frame colours. A board drawn in the browser therefore
matches one drawn here, and tests/test_design_tokens.py fails when the two drift apart.
"""

import argparse
import json
import sys
from pathlib import Path

from . import frames, materials, props
from .geometry import CELL, PAD
from .palette import ES, PERSON_ACCENTS, THEMES
from .svg import FONT_MONO, FONT_SANS, FONT_SERIF
from .tokens import TOKEN

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "web" / "src" / "generated"
HEADER = "Generated by murdoku_lab/visual/art/design_tokens.py; do not edit by hand."


def tokens():
    from murdoku_lab.setter import settings

    setting_tokens = {}
    for setting_id in settings.available():
        pack = settings.load(setting_id)
        visual = pack["visual"]
        frame = frames.get(visual.get("frame"))
        top, bottom = frames.GRADIENTS[frame["fill"]]
        setting_tokens[setting_id] = {
            "name": pack["name"],
            "eyebrow": pack.get("eyebrow", ""),
            "accent": visual.get("accent", ES["accent"]),
            "frame": {
                "top": top,
                "bottom": bottom,
                "edge": frame["edge"],
                "rim": frame["rim"],
                "axis": frame["axis"],
                "halo": frame["halo"],
                "caps": list(frame["caps"]),
            },
        }
    return {
        "schema": "murdoku.design_tokens/1",
        "note": HEADER,
        "geometry": {
            "cell": CELL,
            "pad": PAD,
            "wall_face": materials.FACE,
            "overhang": props.OVERHANG,
            "frame_margin": frames.MARGIN,
        },
        "token": TOKEN,
        "fonts": {"sans": FONT_SANS, "mono": FONT_MONO, "serif": FONT_SERIF},
        "brand": dict(ES),
        "themes": {name: dict(colours) for name, colours in THEMES.items()},
        "person_accents": list(PERSON_ACCENTS),
        "settings": setting_tokens,
    }


def _css_name(key):
    return key.replace("_", "-")


def css(values=None):
    values = values or tokens()
    lines = [f"/* {HEADER} */", ":root {"]
    for key, value in values["geometry"].items():
        lines.append(f"  --mk-{_css_name(key)}: {value};")
    for key in ("sans", "mono", "serif"):
        lines.append(f"  --mk-font-{key}: {values['fonts'][key]};")
    for key, value in values["brand"].items():
        lines.append(f"  --es-{_css_name(key)}: {value};")
    for key, value in values["themes"]["day"].items():
        lines.append(f"  --mk-{_css_name(key)}: {value};")
    for i, value in enumerate(values["person_accents"]):
        lines.append(f"  --mk-person-{i}: {value};")
    lines.append("}")
    lines.append(':root[data-theme="night"] {')
    for key, value in values["themes"]["night"].items():
        if value != values["themes"]["day"].get(key):
            lines.append(f"  --mk-{_css_name(key)}: {value};")
    lines.append("}")
    for setting_id, entry in values["settings"].items():
        frame = entry["frame"]
        lines.append(f'[data-setting="{setting_id}"] {{')
        lines.append(f"  --mk-setting-accent: {entry['accent']};")
        lines.append(f"  --mk-frame-top: {frame['top']};")
        lines.append(f"  --mk-frame-bottom: {frame['bottom']};")
        lines.append(f"  --mk-frame-edge: {frame['edge']};")
        lines.append(f"  --mk-frame-axis: {frame['axis']};")
        lines.append(f"  --mk-frame-halo: {frame['halo']};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def rendered():
    values = tokens()
    return {
        "tokens.json": json.dumps(values, indent=2, sort_keys=True) + "\n",
        "tokens.css": css(values),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    files = rendered()
    if args.write:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, body in files.items():
            (OUT / name).write_text(body)
        print(f"wrote {', '.join(files)} to {OUT}")
        return 0
    stale = [
        name
        for name, body in files.items()
        if not (OUT / name).exists() or (OUT / name).read_text() != body
    ]
    if stale:
        print("design tokens drifted: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
